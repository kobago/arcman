export type Lang = 'ja' | 'en'
export type T = (key: Key, vars?: Record<string, string | number>) => string

export const dictionaries: Record<Lang, Record<Key, string>> = { ja, en }


export const I18nContext = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: T } | null>(null)


export function useI18n() {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider')
  return ctx
}

export function errorMessage(t: T, error: unknown): string {
  const code = (error as { code?: string } | null)?.code
  const key = `error.${code}` as Key
  return key in ja ? t(key) : t('error.generic')
}
